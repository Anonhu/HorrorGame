#!/usr/bin/env python3
"""
Сверка заглушек (tools/stubs) с настоящими исходниками библиотек.

Зачем это нужно: заглушки избавляют от Gradle (он недоступен в песочнице), но
сами по себе они — «мои воспоминания об API». Скрипт закрывает эту дыру: берёт
каждый тип, каждый метод (имя + число аргументов) и каждое поле из
`tools/stubs` и ищет их в настоящих исходниках:

  * Minestom, ветка 26_3 (+ автогенерируемые MinecraftConstants/Blocks/Materials);
  * Adventure 5.2.0 — оттуда Player берёт sendMessage/showTitle/playSound.

Поиск идёт и по родителям типа (Player → CommandSender → Audience), поэтому
унаследованные методы тоже проверяются, а не считаются «не найдено».

    python3 tools/verify_stubs.py            по кэшу (быстро, без сети)
    python3 tools/verify_stubs.py --refresh  перекачать исходники и кэш
"""
