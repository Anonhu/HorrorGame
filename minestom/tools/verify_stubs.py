# Часть констант Minestom объявляет в автогенерируемом соседе:
# Block.AIR живёт в Blocks.java, Material.STONE — в Materials.java
COMPANIONS = {
    "net/minestom/server/instance/block/Block.java":
        ["net/minestom/server/instance/block/Blocks.java"],
    "net/minestom/server/item/Material.java":
        ["net/minestom/server/item/Materials.java"],
}

JDK_PARENTS = {
    "Object", "Enum", "Record", "Comparable", "Iterable", "Iterator", "Runnable",
    "Cloneable", "Serializable", "CharSequence", "AutoCloseable", "Number",
    "Throwable", "Exception", "FunctionalInterface", "Override", "Pointered",
}

TYPE_DECL = re.compile(r"\b(class|interface|enum|record)\s+([A-Za-z_]\w*)")
NAME_ARGS = re.compile(r"([A-Za-z_]\w*)\s*\(")
FIELD = re.compile(
    r"^(?:public\s+|protected\s+|private\s+|static\s+|final\s+|volatile\s+|transient\s+)*"
    r"[A-Za-z_][\w.<>\[\],\s?]*\s+([A-Za-z_]\w*)\s*(?:=[^;]*)?;")
STATEMENT = re.compile(
    r"^(return|new|throw|else|case|yield|assert|break|continue|if|for|while|switch|try|do|"
    r"synchronized|var|this|super)\b")
ANNOTATION = re.compile(r"@[\w.]+(?:\([^)]*\))?\s*")


# ─── сеть ────────────────────────────────────────────────────────────────────
def api(path):
    req = urllib.request.Request("https://api.github.com" + path,
                                 headers={"User-Agent": "three-nights-verify"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def read_file(repo, path, ref):
    blob = api(f"{repo}/contents/{path}?ref={ref}")
    if blob.get("encoding") != "base64":
        raise RuntimeError("не файл: " + path)
    return base64.b64decode(blob["content"]).decode("utf-8")


def repo_tree(src):
    d = api(f"{src['repo']}/git/trees/{src['ref']}?recursive=1")
    if d.get("truncated"):
        print("! дерево репозитория урезано, часть файлов не видна:", src["title"])
    out = []
    for t in d["tree"]:
        p = t["path"]
        if t.get("type") == "blob" and p.endswith(".java") and \
                any(p.startswith(root) for root in src["roots"]):
            out.append(p)
    return sorted(out)


# ─── разбор исходников ───────────────────────────────────────────────────────
def clean_java(text):
    """Вырезает комментарии и содержимое литералов, сохраняя переводы строк.

    Один проход именно в таком порядке: если сначала гасить литералы, апострофы
    в комментариях (player's) открывают «строку» и съедают полфайла.
    """
    out, i, n = [], 0, len(text)
    while i < n:
        c = text[i]
        if c == "/" and i + 1 < n and text[i + 1] == "/":
            while i < n and text[i] != "\n":
                out.append(" ")
                i += 1
            continue
        if c == "/" and i + 1 < n and text[i + 1] == "*":
            while i < n and not (text[i] == "*" and i + 1 < n and text[i + 1] == "/"):
                out.append("\n" if text[i] == "\n" else " ")
                i += 1
            out.append("  ")
            i += 2
            continue
        if text.startswith('"""', i):
            out.append("   ")
            i += 3
            while i < n and not text.startswith('"""', i):
                out.append("\n" if text[i] == "\n" else " ")
                i += 1
            out.append("   ")
            i += 3
            continue
        if c in "\"'":
            quote = c
            out.append(c)
            i += 1
            while i < n:
                ch = text[i]
                if ch == "\\" and i + 1 < n:
                    out.append("  ")
                    i += 2
                    continue
                if ch == quote or ch == "\n":
                    out.append(ch)
                    i += 1
                    break
                out.append(" ")
                i += 1
            continue
        out.append(c)
        i += 1
    return "".join(out)


def logical_lines(text):
    """Строки с приклеенными продолжениями объявлений.

    Клеим ровно до баланса скобок — так
        public EventNode<T> addListener(
                Class<E> eventType, Consumer<E> listener) {
    становится одной строкой, а тело метода не «съедает» следующие методы.
    """
    out, buf = [], ""
    for raw in clean_java(text).splitlines():
        s = raw.strip()
        if not s:
            continue
        buf = (buf + " " + s).strip() if buf else s
        if buf.count("(") <= buf.count(")"):
            out.append(buf)
            buf = ""
    if buf:
        out.append(buf)
    return out


def split_top(text):
    """Делит по запятым верхнего уровня: 'int a, Map<String,Integer> b'."""
    if not text.strip():
        return []
    parts, depth, cur = [], 0, ""
    for ch in text:
        if ch in "<([":
            depth += 1
        elif ch in ">)]":
            depth -= 1
        if ch == "," and depth == 0:
            parts.append(cur.strip())
            cur = ""
            continue
        cur += ch
    if cur.strip():
        parts.append(cur.strip())
    return parts


def split_params(text):
    return len(split_top(text))


def args_at(line, open_idx):
    """Содержимое первых парных скобок, начиная с open_idx (позиция '(')."""
    depth = 0
    for i in range(open_idx, len(line)):
        c = line[i]
        if c == "(":
            depth += 1
        elif c == ")":
            depth -= 1
            if depth == 0:
                return line[open_idx + 1:i]
    return None


def strip_generics(text):
    """Убирает <...> с учётом вложенности: 'Map<String,List<E>>' → ''."""
    out, depth = [], 0
    for ch in text:
        if ch == "<":
            depth += 1
        elif ch == ">":
            depth = max(0, depth - 1)
        elif depth == 0:
            out.append(ch)
    return "".join(out)


def parents_of(decl):
    """extends/implements/permits из объявления типа, без дженериков и JDK.

    Квалифицированные имена сохраняются (Block.Getter): иначе «Getter» в
    объявлении Instance некуда привязать.
    """
    out = []
    flat = strip_generics(decl)
    pat = r"\b(?:extends|implements|permits)\s+([^{]*?)(?=\s*\b(?:extends|implements|permits)\b|{)"
    for m in re.finditer(pat, flat):
        for part in split_top(m.group(1)):
            name = re.sub(r"@[\w.]+", "", part).strip()
            if re.fullmatch(r"[A-Za-z_][\w.]*", name or ""):
                out.append(".".join(name.split(".")[-2:]))
    return [p for p in out if p.split(".")[-1] not in JDK_PARENTS]


def merge_decls(lines):
    """Склеивает объявления, разорванные переносом до открывающей скобки:

        public sealed interface SendablePacket
                permits BufferedPacket, CachedPacket {
    """
    out, i = [], 0
    while i < len(lines):
        line = lines[i]
        d = TYPE_DECL.search(line)
        if d and re.fullmatch(r"[\w@\s.\-]*", line[:d.start()]) and not line.endswith(("{", "}")):
            j = i
            while j + 1 < len(lines) and not line.rstrip().endswith("{"):
                j += 1
                line = line + " " + lines[j]
            i = j
        out.append(line)
        i += 1
    return out


def parse_java(text):
    """Модель файла: типы с членами и родителями (вложенные — рекурсивно).

    Возвращает {Имя: {"name", "parents", "methods": [[имя, арность]],
                      "fields": [ИМЯ], "nested": {Имя: тип}}}

    Члены читаются только на глубине тела своего типа — иначе вызов
    new Sound() { } из тела метода притворяется членом интерфейса.
    """
    top, stack = {}, []          # stack: [(node, глубина тела)]
    depth = 0
    for raw in merge_decls(logical_lines(text)):
        line = ANNOTATION.sub(" ", raw).strip()
        if not line:
            continue
        d = TYPE_DECL.search(line)
        starts = bool(d) and "=" not in line[:d.start()] and \
            re.fullmatch(r"[\w@\s.\-]*", line[:d.start()])
        if starts:
            node = {"name": d.group(2), "parents": parents_of(line),
                    "methods": [], "fields": [], "nested": {}}
            (stack[-1][0]["nested"] if stack else top)[d.group(2)] = node
            if d.group(1) == "record":
                o = line.find("(", d.end())
                comps = args_at(line, o) if o >= 0 else None
                names = []
                for comp in split_top(comps or ""):
                    fname = comp.split()[-1].replace("...", "")
                    if re.fullmatch(r"[A-Za-z_]\w*", fname):
                        names.append(fname)
                        node["fields"].append(fname)
                        node["methods"].append([fname, 0])
                node["methods"].append([node["name"], len(names)])   # канонический конструктор
            stack.append((node, depth + 1))
            depth += line.count("{") - line.count("}")
            while stack and depth < stack[-1][1]:
                stack.pop()
            continue
        if stack and depth == stack[-1][1] and not STATEMENT.match(line):
            node = stack[-1][0]
            m = NAME_ARGS.search(line)
            args = None
            if m:
                prefix = line[:m.start(1)]
                if prefix.strip() and "=" not in prefix and "new " not in prefix \
                        and not prefix.strip().endswith("."):
                    args = args_at(line, line.index("(", m.end(1) - 1))
            if args is not None:
                node["methods"].append([m.group(1), split_params(args)])
            else:
                f = FIELD.match(line)
                if f:
                    node["fields"].append(f.group(1))
        depth += line.count("{") - line.count("}")
        while stack and depth < stack[-1][1]:
            stack.pop()
    return top


def members_of(node):
    """(методы, поля) одного типа без родителей."""
    return {tuple(m) for m in node["methods"]}, set(node["fields"])


# ─── индекс исходников ───────────────────────────────────────────────────────
class Index:
    def __init__(self, data):
        self.data = data
        self.types = data["types"]                  # "sid:путь" → разобранный тип
        self.files = {sid: s["files"] for sid, s in data["sources"].items()}

    def save(self):
        json.dump(self.data, open(CACHE, "w"), ensure_ascii=False, separators=(",", ":"))

    def find(self, wanted, prefer=None, near=None):
        """wanted — 'net/minestom/.../Player.java' или просто 'Audience'."""
        hits, is_path = [], wanted.endswith(".java")
        for sid, paths in self.files.items():
            for p in paths:
                if is_path:
                    if p == wanted or p.endswith("/" + wanted):
                        hits.append((sid, p))
                elif p.endswith("/" + wanted + ".java"):
                    hits.append((sid, p))
        if not hits:
            return None

        def score(hit):
            sid, p = hit
            s = 0.0 if sid == prefer else (1.0 if sid == "minestom" else 2.0)
            if near and os.path.dirname(p) == near:
                s -= 0.5
            return (s, len(p))

        return sorted(hits, key=score)[0]

    def load(self, sid, path):
        key = sid + ":" + path
        if key in self.types:
            return self.types[key]
        src = self.data["sources"][sid]
        top = parse_java(read_file(src["repo"], path, src["ref"]))
        if not top:
            return None
        name = path.rsplit("/", 1)[-1][:-5]
        node = top.get(name) or next(iter(top.values()))
        self.types[key] = node
        return node

    def collect(self, sid, path, node, seen=None, depth=0):
        """Методы и поля типа вместе с унаследованными + список неразрешённых родителей."""
        seen = seen or set()
        if (sid, path) in seen or depth > 6:
            return set(), set(), set(), []
        seen.add((sid, path))
        methods, fields = members_of(node)
        unresolved, chain = set(), []
        near = os.path.dirname(path)
        for parent in node["parents"]:
            if "." in parent:                       # Block.Getter
                outer, inner = parent.split(".", 1)
                hit = self.find(outer, prefer=sid, near=near)
                if hit:
                    onode = self.load(*hit)
                    nested = onode["nested"].get(inner) if onode else None
                    if nested is not None:
                        m2, f2, un, c2 = self.collect(hit[0], hit[1] + "#" + inner,
                                                      nested, seen, depth + 1)
                        methods |= m2
                        fields |= f2
                        unresolved |= un
                        chain = chain + [parent] + c2
                        continue
                unresolved.add(parent)
                continue
            nested = node["nested"].get(parent)
            if nested is not None:
                m2, f2, un, c2 = self.collect(sid, path + "#" + parent, nested, seen, depth + 1)
                methods |= m2
                fields |= f2
                unresolved |= un
                chain = chain + [parent] + c2
                continue
            hit = self.find(parent, prefer=sid, near=near)
            if not hit:
                unresolved.add(parent)
                continue
            pnode = self.load(*hit)
            if pnode is None:
                unresolved.add(parent)
                continue
            m2, f2, un, c2 = self.collect(hit[0], hit[1], pnode, seen, depth + 1)
            methods |= m2
            fields |= f2
            unresolved |= un
            chain = chain + [parent] + c2
        return methods, fields, unresolved, chain

    def node_for_stub(self, rel):
        hit = self.find(rel)
        if not hit:
            return None, None, None
        return self.load(*hit), hit[0], hit[1]


# ─── наполнение кэша ─────────────────────────────────────────────────────────
def stub_files():
    out = []
    for base, _dirs, names in os.walk(STUBS):
        for n in names:
            if n.endswith(".java"):
                full = os.path.join(base, n)
                out.append((os.path.relpath(full, STUBS).replace(os.sep, "/"), full))
    return sorted(out)


def refresh():
    print("· качаю деревья репозиториев и sha…")
    data = {"sources": {}, "types": {}}
    for src in SOURCES:
        files = repo_tree(src)
        meta = {"title": src["title"], "repo": src["repo"], "ref": src["ref"], "files": files}
        try:
            meta["commit"] = api(f"{src['repo']}/commits/{src['ref']}")["sha"]
        except Exception:
            meta["commit"] = None
        data["sources"][src["id"]] = meta
        print(f"  {src['title']}: {len(files)} .java, sha {str(meta['commit'])[:7]}")

    idx = Index(data)
    rels = [rel for rel, _full in stub_files()]
    print(f"· разбираю {len(rels)} заглушек и их родителей…")
    queue = [(r, None) for r in sorted(set(rels) | {c for cs in COMPANIONS.values() for c in cs})]
    done = set()
    while queue:
        wanted, sid_hint = queue.pop(0)
        hit = idx.find(wanted, prefer=sid_hint)
        if not hit:
            continue
        sid, path = hit
        if (sid, path) in done:
            continue
        done.add((sid, path))
        node = idx.load(sid, path)
        if node is None:
            continue
        for parent in node["parents"]:
            queue.append((parent, sid))
    print(f"  разобрано файлов: {len(done)}")
    idx.save()
    return idx


def load(refresh_flag):
    if refresh_flag or not os.path.exists(CACHE):
        try:
            return refresh()
        except Exception as e:
            if not os.path.exists(CACHE):
                print("НЕ УДАЛОСЬ получить эталон:", e)
                sys.exit(2)
            print("· сеть недоступна, беру кэш:", e)
    return Index(json.load(open(CACHE)))


# ─── проверка ────────────────────────────────────────────────────────────────
def main():
    idx = load("--refresh" in sys.argv)
    print("эталон:")
    for s in idx.data["sources"].values():
        print(f"  {s['title']}: {str(s.get('commit'))[:7]}")

    fails, checked_types, checked_nested, checked_members, inherited = 0, 0, 0, 0, 0
    external = {}

    for rel, full in stub_files():
        node, sid, path = idx.node_for_stub(rel)
        if node is None:
            fails += 1
            print(f"  FAIL {rel}: такого типа нет ни в Minestom 26.3, ни в Adventure 5.2.0")
            continue

        methods, fields, unresolved, _chain = idx.collect(sid, path, node)
        own_methods, own_fields = members_of(node)
        for comp in COMPANIONS.get(rel, []):
            cnode, csid, cpath = idx.node_for_stub(comp)
            if cnode is not None:
                cm, cf, _u, _c = idx.collect(csid, cpath, cnode)
                methods |= cm
                fields |= cf

        stub_top = parse_java(open(full, encoding="utf-8").read())
        if not stub_top:
            fails += 1
            print(f"  FAIL {rel}: не удалось разобрать файл заглушки")
            continue
        sname = rel.rsplit("/", 1)[-1][:-5]
        snode = stub_top.get(sname) or next(iter(stub_top.values()))
        s_methods, s_fields = members_of(snode)

        bad_m = sorted(m for m in s_methods if m not in methods)
        bad_f = sorted(f for f in s_fields if f not in fields)
        checked_types += 1
        checked_members += len(s_methods) + len(s_fields)
        inh = len((s_methods - own_methods) | (s_fields - own_fields))
        inherited += inh

        for nname, nnode in snode["nested"].items():
            checked_nested += 1
            real_nested = node["nested"].get(nname)
            if real_nested is None:
                fails += 1
                print(f"  FAIL {rel}: вложенного типа {nname} нет в эталоне")
                continue
            nm, nf = members_of(real_nested)
            nsm, nsf = members_of(nnode)
            checked_members += len(nsm) + len(nsf)
            for m in sorted(nsm - nm):
                fails += 1
                print(f"       · {nname}.{m[0]}() с {m[1]} аргум. нет в эталоне")

        if bad_m or bad_f:
            fails += len(bad_m) + len(bad_f)
            print(f"  FAIL {rel}")
            for n, a in bad_m:
                print(f"       · метода {n}() с {a} аргум. нет ни у типа, ни у родителей")
            for f in bad_f:
                print(f"       · поля {f} нет ни у типа, ни у родителей")
        else:
            note = f", {inh} унаследовано" if inh else ""
            print(f"  ok   {rel}  ({len(s_methods)} методов, {len(s_fields)} полей{note})")
        for p in sorted(unresolved):
            external[p] = external.get(p, 0) + 1

    print()
    print(f"проверено типов: {checked_types}, вложенных: {checked_nested}, "
          f"членов: {checked_members}, из них унаследованных: {inherited}")
    if external:
        print("родители вне эталона (JDK/прочее, не сверялись):",
              ", ".join(sorted(external)))
    if fails == 0:
        print("ИТОГ: каждый член каждой заглушки есть в настоящем API — "
              "компиляция против заглушек не может «пройти мимо» ошибки в игре.")
    else:
        print("ИТОГ: расхождений —", fails)
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
