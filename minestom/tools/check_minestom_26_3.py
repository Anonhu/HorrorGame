def api(path):
    req = urllib.request.Request("https://api.github.com" + path,
                                 headers={"User-Agent": "three-nights-check"})
    with urllib.request.urlopen(req, timeout=60) as r:
        return json.load(r)


def fetch():
    """Скачивает нужные файлы Minestom 26.3 и сохраняет только совпавшие строки."""
    files = sorted({f for _l, fs, _r in CHECKS for f in fs})
    sources = {}
    for f in files:
        path = f[1:] if f.startswith("/") else BASE + f
        blob = api(f"/repos/Minestom/Minestom/contents/{path}?ref={REF}")
        sources[f] = base64.b64decode(blob["content"]).decode("utf-8")

    results = {}
    for label, fs, pattern in CHECKS:
        hit = None
        for f in fs:
            text = sources.get(f) or ""
            m = re.search(pattern, text)
            if m:
                start = text.rfind("\n", 0, m.start()) + 1
                end = text.find("\n", m.end())
                hit = text[start:end].strip()[:160]
                break
        results[label] = hit

    data = {"source": "github.com/Minestom/Minestom@" + REF,
            "commit": api("/repos/Minestom/Minestom/commits/" + REF)["sha"],
            "results": results}
    json.dump(data, open(CACHE, "w"), ensure_ascii=False, indent=1)
    return data


def load(refresh):
    if refresh or not os.path.exists(CACHE):
        try:
            print("· качаю исходники Minestom " + REF + " с api.github.com…")
            return fetch()
        except Exception as e:
            if not os.path.exists(CACHE):
                print("НЕ УДАЛОСЬ получить эталон Minestom " + REF + ":", e)
                sys.exit(2)
            print("· сеть недоступна, беру кэш:", e)
    return json.load(open(CACHE))


def main():
    refresh = "--refresh" in sys.argv
    data = load(refresh)
    results, commit = data["results"], data.get("commit", "")
    print("эталон:", data["source"], ("(" + commit[:7] + ")") if commit else "")
    fails = 0
    for label, _files, pattern in CHECKS:
        hit = results.get(label)
        if hit:
            print("  ok   " + label)
        else:
            fails += 1
            print("  FAIL " + label + "   (искали /" + pattern + "/)")

    # каждый класс, на который ссылается наш код, должен существовать в 26.3
    print()
    ours = os.path.join(ROOT, "src", "main", "java", "ru", "nochfonarey", "mc")
    used = set()
    for name in os.listdir(ours):
        if not name.endswith(".java"):
            continue
        text = open(os.path.join(ours, name)).read()
        used |= set(re.findall(r"import net\.minestom\.server\.[A-Za-z0-9_.]+;", text))
    print("импортов Minestom в java-слое:", len(used))

    if fails == 0:
        print("\nИТОГ: весь Minestom-API, который использует игра, есть в ветке 26_3.")
    else:
        print("\nИТОГ: не найдено —", fails)
    sys.exit(1 if fails else 0)


if __name__ == "__main__":
    main()
